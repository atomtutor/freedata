// CSV/붙여넣기 텍스트를 파싱하고, 컬럼별로 "범주형/수치형/식별자/시간"을
// 자동으로 판별하는 스키마 감지 엔진.
// 어떤 설문지를 올려도(컬럼명이 달라도) 자동으로 인식되도록 설계했습니다.
// ─────────────────────────────────────────────────────────

const ID_HEADER_RE = /(닉네임|이름|성명|name|nickname)/i;
const TIME_HEADER_RE = /(타임스탬프|timestamp|시각|일시|날짜|date)/i;

// 바이트 데이터를 텍스트로 디코딩한다. 대부분의 CSV(특히 구글 시트 내보내기)는 UTF-8이지만,
// 엑셀에서 "CSV(쉼표로 분리)"로 저장한 한글 파일은 종종 EUC-KR/CP949로 인코딩되어 있어
// 그대로 UTF-8로 읽으면 한글이 깨진다. UTF-8로 우선 시도해보고(fatal 모드로 엄격하게 검사),
// 유효하지 않은 바이트 시퀀스가 있으면(=UTF-8이 아니면) EUC-KR로 다시 시도한다.
function decodeBytes(buffer) {
  try {
    return new TextDecoder('utf-8', { fatal: true }).decode(buffer);
  } catch (e) {
    try {
      return new TextDecoder('euc-kr').decode(buffer);
    } catch (e2) {
      return new TextDecoder('utf-8').decode(buffer); // 최후 수단: 깨지더라도 일단 표시
    }
  }
}

function emptySchema() { return { idKey: null, timeKey: null, categorical: [], numeric: [], isPerson: false }; }

// 스키마를 보고 "명"(사람) / "건"(사물·일반) 중 알맞은 단위 라벨을 돌려준다.
// idKey가 "닉네임/이름/성명" 같은 사람 이름 패턴으로 찾아졌을 때만 "명"을 쓰고,
// 그 외(식별자가 없거나 상품명 등으로 대체된 경우)는 중립적인 "건"을 쓴다.
function getUnitLabel(schema) { return (schema && schema.isPerson) ? '명' : '건'; }

// 컬럼별로 범주형/수치형/식별자/시간을 자동 판별
function detectSchema(headers, rawRows) {
  const schema = emptySchema();
  const total = rawRows.length;

  headers.forEach(h => {
    if (!schema.timeKey && TIME_HEADER_RE.test(h)) { schema.timeKey = h; return; }
    if (!schema.idKey && ID_HEADER_RE.test(h)) { schema.idKey = h; schema.isPerson = true; return; }

    const vals = rawRows.map(r => r[h]).filter(v => v !== undefined && v !== '');
    if (!vals.length) return; // 값이 전부 비어있으면 스킵

    const numericVals = vals.filter(v => v !== '' && !isNaN(Number(v)));
    const isNumeric = numericVals.length / vals.length >= 0.9;

    if (isNumeric) {
      schema.numeric.push(h);
    } else {
      const uniq = Array.from(new Set(vals));
      // 범주형으로 다루기 적당한 값 개수(2~8개)만 채택.
      // 그보다 많으면(자유서술형 등) 드롭다운이 지저분해지므로 분석 대상에서 제외.
      if (uniq.length >= 2 && uniq.length <= 8 && uniq.length < total) {
        schema.categorical.push({ key: h, values: uniq });
      }
    }
  });

  // 닉네임/이름 헤더를 못 찾았다면, 값이 전부 고유한 텍스트 컬럼을 식별자로 채택
  if (!schema.idKey) {
    for (const h of headers) {
      if (h === schema.timeKey) continue;
      if (schema.numeric.includes(h)) continue;
      if (schema.categorical.some(c => c.key === h)) continue;
      const vals = rawRows.map(r => r[h]).filter(Boolean);
      const uniq = new Set(vals);
      if (vals.length && uniq.size === vals.length) { schema.idKey = h; break; }
    }
  }

  return schema;
}

// 스키마에 따라 값 타입 변환 + 표시용 이름표(__label) 부여
function typeRows(rawRows, schema) {
  return rawRows.map((r, i) => {
    const row = {};
    Object.keys(r).forEach(h => {
      row[h] = schema.numeric.includes(h) ? (Number(r[h]) || 0) : r[h];
    });
    row.__label = (schema.idKey && row[schema.idKey]) ? String(row[schema.idKey]) : `${getUnitLabel(schema)}${i + 1}`;
    return row;
  });
}

// CSV/TSV 텍스트 → { headers, rows, schema }
function parseCSV(text) {
  if (!text || !String(text).trim()) return { headers: [], rows: [], schema: emptySchema() };
  text = text.replace(/\uFEFF/g, ''); // BOM 제거
  const lines = String(text).trim().split(/\r?\n/).filter(Boolean);
  if (lines.length < 2) return { headers: [], rows: [], schema: emptySchema() };

  const headerLine = lines[0];
  const commaCount = (headerLine.match(/,/g) || []).length;
  const tabCount = (headerLine.match(/\t/g) || []).length;
  const delim = tabCount > commaCount ? '\t' : ',';

  const rawHeaders = headerLine.split(delim).map(h => h.trim()).filter(h => h !== '');
  // 헤더 중복 시 뒤에 번호 붙이기 (예: "메모","메모" → "메모","메모_2")
  const seen = {};
  const headers = rawHeaders.map(h => {
    seen[h] = (seen[h] || 0) + 1;
    return seen[h] > 1 ? `${h}_${seen[h]}` : h;
  });

  const rawRows = lines.slice(1).map(line => {
    const cols = line.split(delim);
    const r = {};
    headers.forEach((h, i) => { r[h] = (cols[i] === undefined ? '' : cols[i].trim()); });
    return r;
  });

  const schema = detectSchema(headers, rawRows);
  const rows = typeRows(rawRows, schema);

  return { headers, rows, schema };
}

